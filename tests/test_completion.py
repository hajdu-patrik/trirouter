from trirouter import cli, completion as C, manual, platforms as P


def all_long_flags():
    return {f.long for c in manual.COMMANDS.values() for f in manual.all_flags(c)}


@pytest.mark.parametrize("shell", C.SHELLS)
def test_every_command_subcommand_flag_and_value_is_in_the_script(shell):
    text = C.script(shell)
    for c in manual.ORDER:
        assert c in text
    for subs in manual.SUBCOMMANDS.values():
        for s in subs:
            assert s in text
    for flag in all_long_flags():
        assert (flag if shell != "fish" else f"-l {flag[2:]}") in text, flag
    for value in ("claude-chat", "on", "off"):
        assert value in text
    assert "generated by `trirouter setup`" in text
    body = chr(10).join(x for x in text.splitlines() if not x.lstrip().startswith("#"))  # without comments
    for doc in (d for _, _, d in manual.TOP_FLAGS):
        body = body.replace(doc.rstrip("."), "")
    for gone in ("--probe", "--shell", "--install"):
        assert gone not in body, gone
    for line in (x for x in body.splitlines() if "uninstall" in x):  # the places that list the commands
        for gone in ("detect", "completion", "version"):
            assert not re.search(rf"(?<![\w-]){gone}(?![\w-])", line), (gone, line)
    for flag in ("--version", "-V"):
        assert (flag if shell != "fish" else {"--version": "-l version", "-V": "-s V"}[flag]) in text, flag


def test_value_flags_end_in_equals_and_values_follow_the_hint():
    assert C.flags_of("models") == ["--discover", "--auto=", "--main=", "--subagent-model=", "--dry-run", "--help"]
    auto = next(f for f in manual.COMMANDS["models"].flags if f.long == "--auto")
    assert C.values_of(auto) == ["on", "off"]
    provider = next(f for f in manual.COMMANDS["route"].flags if f.long == "--provider")
    assert C.values_of(provider) == ["claude", "codex", "antigravity", "claude-chat"]
    providers = next(f for f in manual.COMMANDS["setup"].flags if f.long == "--providers")
    assert C.values_of(providers) == list(P.PROVIDER_NAMES)


