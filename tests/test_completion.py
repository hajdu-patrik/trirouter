@pytest.fixture
def os_sim(monkeypatch, tmp_path):
    def set_os(name, pwsh=False):
        monkeypatch.setattr(P, "IS_WINDOWS", name == "windows")
        monkeypatch.setattr(P, "IS_MAC", name == "mac")
        monkeypatch.setattr(P, "HOME", tmp_path / "home")
        monkeypatch.setattr(P, "find_exe", lambda exe: f"/usr/bin/{exe}" if pwsh and exe == "pwsh" else None)
        for var in ("SHELL", "ZDOTDIR", "XDG_CONFIG_HOME"):
            monkeypatch.delenv(var, raising=False)
    return set_os


@pytest.mark.parametrize("osname, shell_env, pwsh, expected", [
    ("windows", None, False, ["powershell"]),
    ("windows", "/usr/bin/bash", False, ["bash", "powershell"]),        # Git Bash
    ("mac", None, False, ["zsh"]),                                      # macOS default shell
    ("mac", "/bin/bash", True, ["bash", "powershell"]),
    ("linux", None, False, ["bash"]),
    ("linux", "/usr/bin/fish", False, ["fish"]),
    ("linux", "/bin/zsh", True, ["zsh", "powershell"]),
])
def test_setup_picks_the_shells_per_os(os_sim, osname, shell_env, pwsh, expected):
    os_sim(osname, pwsh)
    env = {"SHELL": shell_env} if shell_env else {}
    assert C.setup_shells(env) == expected
    assert C.detect_shell(env) == expected[0]


def test_profiles_per_os(os_sim, monkeypatch, tmp_path):
    home = tmp_path / "home"
    os_sim("mac")
    assert C.profiles("bash") == [home / ".bash_profile"]   # macOS login shells skip ~/.bashrc
    assert C.profiles("zsh") == [home / ".zshrc"]
    os_sim("linux")
    assert C.profiles("bash") == [home / ".bashrc"]
    monkeypatch.setenv("ZDOTDIR", str(tmp_path / "zdot"))
    assert C.profiles("zsh") == [tmp_path / "zdot" / ".zshrc"]
    assert C.profiles("fish") == [] and C.profile_block("fish") is None
    assert C.script_path("fish") == home / ".config" / "fish" / "completions" / "trirouter.fish"
    monkeypatch.setenv("XDG_CONFIG_HOME", str(tmp_path / "xdg"))
    assert C.script_path("fish") == tmp_path / "xdg" / "fish" / "completions" / "trirouter.fish"
    os_sim("windows")
    assert C.profiles("bash") == [home / ".bashrc"]  # Git Bash: its ~/.bash_profile sources ~/.bashrc


def test_powershell_profiles_are_asked_from_each_edition(os_sim, monkeypatch, tmp_path):
    os_sim("windows")
    monkeypatch.setattr(P, "find_exe", lambda exe: exe if exe in ("pwsh", "powershell") else None)
