"""Installs or removes the hooks and MCP server for Claude Code, Codex and Antigravity, and the `trirouter` launcher.
Every entry calls a shim in ~/.trirouter/bin, so moving the repository only means re-running setup."""
import json
import ntpath
import os
import re
from pathlib import Path

from . import core, platforms as P

BIN = P.STATE / "bin"
SHIM_HOOK, SHIM_MCP, SHIM_ROUTE = BIN / "run_hook.py", BIN / "mcp_server.py", BIN / "route.py"
LOCAL_BIN = P.HOME / ".local" / "bin"  # macOS / Linux: where the `trirouter` link goes
ALL = P.PROVIDER_NAMES
MCP_NAME = "trirouter"  # server name in the tools' configs
SHIM_TEMPLATE = '''# generated by trirouter's installer - runs {target} from the repository
import runpy, sys
sys.path.insert(0, r"{repo}")
{argv}runpy.run_module("{module}", run_name="__main__", alter_sys=True)
'''
# The hook shim exits 0 whatever happens (a moved checkout, a half-edited module): a failing hook would
# block every prompt of the host tool.
HOOK_SHIM_TEMPLATE = '''# generated by trirouter's installer - runs {target} from the repository; a hook never fails the host
import runpy, sys
sys.path.insert(0, r"{repo}")
try:
    runpy.run_module("{module}", run_name="__main__", alter_sys=True)
except SystemExit:
    pass
except BaseException as exc:
    print(f"trirouter hook: {{type(exc).__name__}}: {{exc}}"[:200], file=sys.stderr)
sys.exit(0)
'''


def shim(module, command=None, hook=False):
    """Shim source that runs `module` from this repository; `command` becomes its first argument; `hook` makes it
    exit 0 whatever happens."""
    argv = f'sys.argv[1:1] = ["{command}"]\n' if command else ""
    target = f"{module} {command}" if command else module
    return (HOOK_SHIM_TEMPLATE if hook else SHIM_TEMPLATE).format(target=target, repo=P.REPO, module=module, argv=argv)


class Writer:
    def __init__(self, apply):
        self.apply = apply
        self.changes = 0
        self.failed = 0

    def write(self, path, content, label):
        path = Path(path)
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old == content:
            print(f"[OK]  {label}: up to date")
            return
        self.changes += 1
        print(("[DO]  " if self.apply else "[DRY] ") + f"{label}: {'update' if old is not None else 'create'} {path}")
        if self.apply:
            P.write_backed_up(path, content)

    def write_json(self, path, cfg, label):
        self.write(path, json.dumps(cfg, indent=2, ensure_ascii=False) + "\n", label)


def fwd(p):
    return str(p).replace("\\", "/")


class BadConfig(Exception):
    pass


def load(path):
    path = Path(path)
    if not path.exists():
        return {}
    try:
        text = path.read_text(encoding="utf-8-sig")
        data = json.loads(text) if text.strip() else {}
    except (ValueError, OSError) as exc:
        raise BadConfig(f"{path} is not valid JSON ({exc}) - fix it, then re-run") from exc
    if not isinstance(data, dict):
        raise BadConfig(f"{path} does not contain a JSON object - fix it, then re-run")
    return data


HOOK_MARKERS = ("trirouter.hooks", ".trirouter/bin/run_hook.py")  # a hook command of ours mentions one of these


def is_router_cmd(cmd):
    c = (cmd or "").replace("\\", "/").lower()
    return (any(m in c for m in HOOK_MARKERS)
            or fwd(SHIM_HOOK).lower() in c or fwd(P.short_path(SHIM_HOOK)).lower() in c)


def hook_cmd(provider, event):
    return f"{P.python_cmd()} {P.shell_arg(SHIM_HOOK)} {provider} {event}"


# An http hook is ours when it posts to the local daemon's /hook/<provider>/ path (any port: daemon.port may change).
ROUTER_URL_RE = re.compile(r"^http://(?:127\.0\.0\.1|localhost)(?::\d+)?/hook/(?:claude|codex|antigravity)/", re.I)


def is_router_url(url):
    return isinstance(url, str) and bool(ROUTER_URL_RE.match(url.strip()))


def is_router_hook(hook):
    """One hook entry of ours: a command running our shim or module, or an http hook to the daemon."""
    if not isinstance(hook, dict):
        return False
    return is_router_cmd(hook.get("command")) or (hook.get("type") == "http" and is_router_url(hook.get("url")))


# http transport (config.json hooks.transport): all events of an http provider except SessionStart, which starts the
# daemon. Codex and Antigravity have no http hooks.
HTTP_PROVIDERS = ("claude",)
COMMAND_ONLY_EVENTS = frozenset({"SessionStart"})
HTTP_HOOK_TIMEOUT_S = 10


def uses_http(provider, event, transport):
    return transport == "http" and provider in HTTP_PROVIDERS and event not in COMMAND_ONLY_EVENTS


def hook_entry(provider, event, transport="command", token=None):
    """The hook entry for one event: an http hook to the daemon, or a command running the hook shim."""
    if uses_http(provider, event, transport):
        from . import daemon
        return {"type": "http", "url": f"http://{daemon.HOST}:{daemon.configured_port()}/hook/{provider}/{event}",
                "headers": {daemon.TOKEN_HEADER: token or "<created on --apply>"}, "timeout": HTTP_HOOK_TIMEOUT_S}
    return {"type": "command", "command": hook_cmd(provider, event), "timeout": 10}


def _router_hooks(cfg):
    """Every hook entry of ours in a parsed settings.json / hooks.json."""
    return (h for groups in (cfg.get("hooks") or {}).values() if isinstance(groups, list)
            for g in groups if isinstance(g, dict) for h in g.get("hooks", []) if is_router_hook(h))


def http_hook_tokens(cfg):
    """The tokens our http hooks in a parsed settings.json send (for doctor: do they match the daemon's?)."""
    from . import daemon
    return {h.get("headers", {}).get(daemon.TOKEN_HEADER) for h in _router_hooks(cfg)
            if h.get("type") == "http" and isinstance(h.get("headers"), dict)} - {None}


def has_router_hooks(path):
    """The config file holds at least one router hook (command or http)."""
    try:
        return any(_router_hooks(load(path)))
    except BadConfig:
        return False


def _strip_router(groups):
    kept = []
    for g in groups or []:
        hs = [h for h in g.get("hooks", []) if not is_router_hook(h)]
        if hs:
            kept.append({**g, "hooks": hs})
    return kept


HOOK_EVENTS = {
    # Stop, StopFailure, SessionEnd release the queue; SubagentStart logs the delegate; SessionStart starts the daemon
    # and the daily checks; PostModelSwitch records the model; PreToolUse (Agent tool) guards the subagent budget
    "claude": ("UserPromptSubmit", "Stop", "StopFailure", "SessionEnd", "SubagentStart", "SessionStart",
               "PostModelSwitch", "PreToolUse"),
    "codex": ("UserPromptSubmit", "Stop"),
}
# (provider, event) -> the hook group's "matcher"; an event not listed gets a group without one
HOOK_MATCHERS = {
    ("codex", "UserPromptSubmit"): "*",
    ("claude", "PreToolUse"): "^(Agent|Task)$",  # the subagent tool (Task: its former name); anchored: not TaskCreate
}
ROUTER_EVENTS = tuple(dict.fromkeys(e for events in HOOK_EVENTS.values() for e in events))


def claude_codex_hooks(path, provider, w, uninstall=False, claude_models=None, transport=None):
    """transport "http" or "command" (None: config.json hooks.transport; only Claude has http hooks). claude_models: the
    (main, subagent) model defaults, re-applied in the same write; uninstall removes the values trirouter set."""
    cfg = load(path)
    hooks = cfg.setdefault("hooks", {})
    wanted = () if uninstall else HOOK_EVENTS[provider]
    transport = transport or core.hook_transport()
    token = None
    if any(uses_http(provider, e, transport) for e in wanted):
        from . import daemon
        token = daemon.token(create=w.apply)  # a dry run never creates the token file
    for event in ROUTER_EVENTS:
        if event not in hooks and event not in wanted:
            continue
        groups = _strip_router(hooks.get(event))
        matcher = HOOK_MATCHERS.get((provider, event))
        if event in wanted:
            entry = {"hooks": [hook_entry(provider, event, transport, token)]}
            groups.append({"matcher": matcher, **entry} if matcher else entry)
        if groups:
            hooks[event] = groups
        else:
            hooks.pop(event, None)
    if not hooks:
        cfg.pop("hooks", None)
    if provider == "claude" and claude_models:
        (_forget_claude_models if uninstall else _reapply_claude_models)(cfg, claude_models)
    w.write_json(path, cfg, f"{provider} hooks")


SUBAGENT_MODEL_ENV = "CLAUDE_CODE_SUBAGENT_MODEL"


def claude_families():
    """The Claude families that may be set as a default: the selectable ones (models.json + per-account overrides)."""
    return [m for m in core.models_for("claude") if core.claude_alias_allowed(m)]


def _check_family(value, what):
    if value is None or value == "off":
        return value
    family = str(value).strip().lower()
    allowed = claude_families()
    if family not in allowed:
        raise ValueError(f"{what}: '{value}' is not a selectable Claude family (one of {', '.join(allowed)}, or off)")
    return family


def apply_claude_models(cfg, main_model=None, subagent_model=None):
    """Sets, in a parsed settings.json, the default family of the main session (`model`) and of subagents that pin none
    (env.CLAUDE_CODE_SUBAGENT_MODEL). "off" removes the key, None leaves it; ValueError before anything changes."""
    main_model = _check_family(main_model, "main model")
    subagent_model = _check_family(subagent_model, "subagent model")
    if main_model == "off":
        cfg.pop("model", None)
    elif main_model:
        cfg["model"] = main_model
    if subagent_model is not None:
        env = cfg.get("env") if isinstance(cfg.get("env"), dict) else {}
        if subagent_model == "off":
            env.pop(SUBAGENT_MODEL_ENV, None)
        else:
            env[SUBAGENT_MODEL_ENV] = subagent_model
        if env:
            cfg["env"] = env
        else:
            cfg.pop("env", None)
    return cfg


def claude_model_settings(w, main_model=None, subagent_model=None, path=None):
    """Writes the Claude model defaults into ~/.claude/settings.json through the Writer: a selectable family, "off"
    (remove) or None (leave); ValueError for an unknown family, BadConfig for a settings.json that is not an object."""
    path = Path(path or P.PATHS["claude_settings"])
    cfg = apply_claude_models(load(path), main_model, subagent_model)
    if not cfg and not path.exists():
        print("[OK]  claude model defaults: nothing to remove")
        return
    w.write_json(path, cfg, "claude model defaults")


def remembered_claude_models(cfg=None):
    """(main, subagent) from config.json `claude.main_model` / `claude.subagent_model` (stored by `trirouter models
    --main / --subagent-model`): each a family, "off" or None. A value that is no longer valid becomes None."""
    if cfg is None:
        cfg = core.user_config()
    claude = cfg.get("claude") if isinstance(cfg, dict) and isinstance(cfg.get("claude"), dict) else {}
    out = []
    for key in ("main_model", "subagent_model"):
        try:
            out.append(_check_family(claude.get(key), key))
        except ValueError:
            out.append(None)
    return tuple(out)


def _reapply_claude_models(cfg, remembered):
    """Setup: a remembered family is written again; a remembered "off" was applied once by the `models` command and
    is not repeated, so a value the user set in settings.json by hand later is kept."""
    apply_claude_models(cfg, *(None if v == "off" else v for v in remembered))


def _forget_claude_models(cfg, remembered):
    """Uninstall: removes only what trirouter set (a key still equal to the remembered family)."""
    main, sub = remembered
    if main not in (None, "off") and cfg.get("model") == main:
        cfg.pop("model", None)
    env = cfg.get("env")
    if sub not in (None, "off") and isinstance(env, dict) and env.get(SUBAGENT_MODEL_ENV) == sub:
        env.pop(SUBAGENT_MODEL_ENV, None)
        if not env:
            cfg.pop("env", None)


AGY_EVENTS = ("PreToolUse", "PostToolUse", "PreInvocation", "PostInvocation", "Stop")


def _strip_router_events(spec):
    for event in ("PreInvocation", "Stop"):
        if event in spec:
            spec[event] = [h for h in spec[event] if not is_router_cmd(h.get("command"))]
            if not spec[event]:
                del spec[event]


def antigravity_hooks(path, w, uninstall=False):
    cfg = load(path)
    for spec in cfg.values():
        if isinstance(spec, dict):
            _strip_router_events(spec)
    cfg = {name: spec for name, spec in cfg.items()
           if not isinstance(spec, dict) or any(k in spec for k in AGY_EVENTS)}
    if not uninstall:
        cfg["router"] = {e: [{"type": "command", "command": hook_cmd("antigravity", e), "timeout": 10}]
                         for e in ("PreInvocation", "Stop")}
    w.write_json(path, cfg, "antigravity hooks")


def json_mcp(path, label, w, uninstall=False):
    cfg = load(path)
    servers = cfg.setdefault("mcpServers", {})
    if uninstall:
        servers.pop(MCP_NAME, None)
    else:
        # MCP clients exec "command" directly, without a shell: never shell-quoted
        servers[MCP_NAME] = {"command": fwd(P.python_exe_windowless()), "args": [fwd(SHIM_MCP)]}
    w.write_json(path, cfg, label)


def codex_mcp(path, w, uninstall=False):
    text = Path(path).read_text(encoding="utf-8-sig") if Path(path).exists() else ""
    # The section ends at the next table or comment line (our agents block starts with one); the first one found is
    # replaced in place, any further one is dropped.
    pat = re.compile(r"\[mcp_servers\." + re.escape(MCP_NAME) + r"\]\n(?:\n|[^\[#\n].*(?:\n|\Z))*")
    block = (f'[mcp_servers.{MCP_NAME}]\ncommand = {json.dumps(fwd(P.python_exe_windowless()))}\n'
             f'args = [{json.dumps(fwd(SHIM_MCP))}]\n\n')
    seen = []

    def replace(_match):
        seen.append(1)
        return block if len(seen) == 1 and not uninstall else ""
    new = pat.sub(replace, text)
    if not seen and not uninstall:
        new = (text.rstrip("\n") + "\n\n" if text.strip() else "") + block
    w.write(path, new, "codex MCP")


def claude_desktop_mcp(w, uninstall=False):
    """The desktop app rewrites the file from memory: a change made while it runs is lost."""
    before = w.changes
    json_mcp(P.claude_desktop_config(), "claude desktop MCP (Chat/Cowork)", w, uninstall)
    if w.changes > before and P.app_running("Claude"):
        print("[!!]  The Claude desktop app is running: quit it completely (tray icon > Quit) and reopen it, "
              "or it overwrites this change")
def install_shims(w):
    w.write(SHIM_HOOK, shim("trirouter.hooks", hook=True), "hook shim")
    w.write(SHIM_MCP, shim("trirouter.mcp_server"), "MCP shim")
    w.write(SHIM_ROUTE, shim("trirouter", "route"), "route shim")


def install(providers=ALL, apply=False, uninstall=False, launcher=True, claude_models=None):
    """The Writer: .changes files changed (or would change), .failed could not be. claude_models: (main, subagent)
    Claude model defaults to keep in settings.json; None re-applies the ones remembered in config.json."""
    w = Writer(apply)
    if not uninstall:
        install_shims(w)
    if launcher:
        (uninstall_launcher if uninstall else install_launcher)(w)
    if claude_models is None and "claude" in providers:
        try:
            claude_models = remembered_claude_models()
        except Exception:  # noqa: BLE001 - an unreadable catalog or config never stops the setup
            claude_models = (None, None)
    steps = []
    if "claude" in providers:
        steps += [lambda: claude_codex_hooks(P.PATHS["claude_settings"], "claude", w, uninstall, claude_models),
                  lambda: claude_desktop_mcp(w, uninstall)]
    if "codex" in providers:
        steps += [lambda: claude_codex_hooks(P.PATHS["codex_hooks"], "codex", w, uninstall),
                  lambda: codex_mcp(P.PATHS["codex_config"], w, uninstall)]
    if "antigravity" in providers:
        steps += [lambda: antigravity_hooks(P.PATHS["agy_hooks"], w, uninstall),
                  lambda: json_mcp(P.PATHS["agy_mcp"], "antigravity MCP", w, uninstall)]
    for step in steps:
        try:
            step()
        except BadConfig as exc:  # one broken file must not stop the others
            w.failed += 1
            print(f"[FAIL] {exc}")
    return w


LAUNCHER_LABEL = "trirouter command"
LAUNCHER_PY_TEMPLATE = '''# generated by trirouter's installer - runs `python -m trirouter` from the repository
import os, runpy, sys
sys.path.insert(0, r"{repo}")
os.environ["TRIROUTER_PROG"] = "trirouter"
runpy.run_module("trirouter", run_name="__main__", alter_sys=True)
'''
PROFILE_LINE = 'export PATH="$HOME/.local/bin:$PATH"'


def launcher_py_path():
    return BIN / P.LAUNCHER_PY


def launcher_cmd_path():
    return BIN / P.LAUNCHER_CMD


def launcher_py(python=None, windows=None, repo=None):
    """Source of the Python launcher. On POSIX it is the executable itself (shebang to the interpreter);
    on Windows trirouter.cmd runs it."""
    windows = P.IS_WINDOWS if windows is None else windows
    body = LAUNCHER_PY_TEMPLATE.format(repo=repo or P.REPO)
    if windows:
        return body
    exe = python or P.python_exe()
    if any(c.isspace() for c in str(exe)):  # a shebang cannot hold a space: re-exec through sh
        return '#!/bin/sh\n\'\'\'\'exec "' + str(exe) + '" "$0" "$@" # \'\'\'\n' + body
    return f"#!{exe}\n" + body


def launcher_cmd(python=None):
    """trirouter.cmd: the same interpreter as the hooks, python.exe (never pythonw.exe), all arguments passed on."""
    exe = str(python or P.python_exe())
    return f'@echo off\r\nrem generated by the trirouter installer\r\n"{exe}" "%~dp0trirouter.py" %*\r\n'


# --- the Windows user PATH (HKCU\Environment); never the system PATH. Injectable for tests. ---

def _env_key(access):
    import winreg
    return winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment", 0, access)


def user_path_read():
    """(value, registry type) of the user's Path; ("", REG_EXPAND_SZ) when there is none."""
    import winreg
    with _env_key(winreg.KEY_READ) as key:
        try:
            return winreg.QueryValueEx(key, "Path")
        except FileNotFoundError:
            return "", winreg.REG_EXPAND_SZ


def user_path_write(value, kind):
    import winreg
    with _env_key(winreg.KEY_SET_VALUE) as key:
        winreg.SetValueEx(key, "Path", 0, kind, value)


def broadcast_env_change():
    """WM_SETTINGCHANGE, so newly started programs re-read the environment."""
    import ctypes
    result = ctypes.c_ulong()
    ctypes.windll.user32.SendMessageTimeoutW(0xFFFF, 0x001A, 0, "Environment", 0x0002, 5000, ctypes.byref(result))


def _norm_entry(entry):
    entry = entry.strip().strip('"')
    # ntpath explicitly: this is Windows registry logic, and it must compare the same way on every OS
    return ntpath.normcase(ntpath.normpath(ntpath.expandvars(entry))) if entry else ""


def path_has(value, entry):
    return _norm_entry(str(entry)) in {_norm_entry(e) for e in value.split(";")}


def path_with(value, entry):
    """`value` with `entry` appended, unless it is there already (no duplicates)."""
    return value if path_has(value, entry) else (value.rstrip(";") + ";" if value else "") + str(entry)


def path_without(value, entry):
    target = _norm_entry(str(entry))
    return ";".join(e for e in value.split(";") if e and _norm_entry(e) != target)


def posix_path_has(directory, path=None):
    path = os.environ.get("PATH", "") if path is None else path
    return str(directory) in [e.rstrip("/") for e in path.split(os.pathsep)]


def _posix_link_state():
    """"ok" (our link), "missing", or "foreign" (something else is in the way: never overwritten)."""
    link = LOCAL_BIN / "trirouter"
    if link.is_symlink():
        return "ok" if os.path.realpath(link) == os.path.realpath(launcher_py_path()) else "foreign"
    return "foreign" if link.exists() else "missing"


def _file_matches(path, content):
    try:
        return Path(path).read_bytes().decode("utf-8").replace("\r\n", "\n") == content.replace("\r\n", "\n")
    except (OSError, ValueError):
        return False


def _write_launcher(path, content):
    P.atomic_write(path, content, mode=None if P.IS_WINDOWS else 0o755, newline="")  # line endings kept exactly


def _make_posix_link():
    LOCAL_BIN.mkdir(parents=True, exist_ok=True)
    os.symlink(launcher_py_path(), LOCAL_BIN / "trirouter")


def _set_user_path(value, kind):
    user_path_write(value, kind)
    broadcast_env_change()


def launcher_plan():
    """[(message, action)] still to do for the `trirouter` command; an empty list means up to date."""
    plan = []
    files = [(launcher_py_path(), launcher_py())]
    if P.IS_WINDOWS:
        files.append((launcher_cmd_path(), launcher_cmd()))
    for path, content in files:
        if not _file_matches(path, content) or (not P.IS_WINDOWS and not os.access(path, os.X_OK)):
            plan.append((f"{'update' if Path(path).exists() else 'create'} {path}",
                         lambda path=path, content=content: _write_launcher(path, content)))
    if P.IS_WINDOWS:
        value, kind = user_path_read()
        if not path_has(value, BIN):
            plan.append((f"add {BIN} to your user PATH", lambda: _set_user_path(path_with(value, BIN), kind)))
    elif _posix_link_state() == "missing":
        plan.append((f"link {LOCAL_BIN / 'trirouter'} -> {launcher_py_path()}", _make_posix_link))
    return plan


def _run_plan(w, plan):
    for message, action in plan:
        w.changes += 1
        print(("[DO]  " if w.apply else "[DRY] ") + f"{LAUNCHER_LABEL}: {message}")
        if w.apply:
            try:
                action()
            except OSError as exc:
                w.failed += 1
                print(f"[FAIL] {LAUNCHER_LABEL}: {exc}")


def install_launcher(w):
    """Writes the `trirouter` launcher and puts it on PATH (user PATH on Windows; on POSIX only a link in
    ~/.local/bin: shell profiles are never edited, the line to add is printed)."""
    plan = launcher_plan()
    if not plan:
        print(f"[OK]  {LAUNCHER_LABEL}: up to date")
    _run_plan(w, plan)
    if P.IS_WINDOWS:
        if plan and w.apply:
            print("[!!]  Terminals that are already open keep the old PATH: close and reopen them, "
                  "then run `trirouter help`.")
    elif _posix_link_state() == "foreign":
        print(f"[!!]  {LOCAL_BIN / 'trirouter'} exists and is not this launcher: left alone. "
              f"Run it directly: {launcher_py_path()}")
    elif not posix_path_has(LOCAL_BIN):
        print(f"[!!]  {LOCAL_BIN} is not on your PATH. Add this line to your shell profile "
              f"(~/.bashrc, ~/.zshrc, ...), then open a new terminal:\n          {PROFILE_LINE}")


def uninstall_launcher(w):
    """Removes the launcher, the ~/.local/bin link (only ours) and the PATH entry."""
    todo = []
    for name in (P.LAUNCHER_PY, P.LAUNCHER_CMD) if P.IS_WINDOWS else (P.LAUNCHER_PY,):
        path = BIN / name
        if path.exists():
            todo.append((f"remove {path}", lambda path=path: Path(path).unlink()))
    if not P.IS_WINDOWS and _posix_link_state() == "ok":
        todo.append((f"remove {LOCAL_BIN / 'trirouter'}", lambda: (LOCAL_BIN / "trirouter").unlink()))
    if P.IS_WINDOWS:
        value, kind = user_path_read()
        if path_has(value, BIN):
            todo.append((f"remove {BIN} from your user PATH", lambda: _set_user_path(path_without(value, BIN), kind)))
    if not todo:
        print(f"[OK]  {LAUNCHER_LABEL}: not installed")
    _run_plan(w, todo)


def launcher_status():
    """(ok, detail) for `doctor`: the launcher exists and its folder is on PATH."""
    present = launcher_py_path().is_file() and (not P.IS_WINDOWS or launcher_cmd_path().is_file())
    if not present:
        return False, f"missing - run: {P.command_hint('setup --yes')}"
    try:
        on_path = path_has(user_path_read()[0], BIN) if P.IS_WINDOWS else (
            _posix_link_state() == "ok" and posix_path_has(LOCAL_BIN))
    except OSError:
        on_path = False
    where = launcher_cmd_path() if P.IS_WINDOWS else launcher_py_path()
    if not on_path:
        return False, f"{where} is installed, but not on PATH - run: {P.command_hint('setup --yes')}"
    return True, f"{where} (on PATH)"
